import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { codenameFor, type Registry } from "@kamino/brand";

const serverRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = resolve(serverRoot, "../..");

function resolveCommit(): string {
  const fromEnv = process.env["KAMINO_BUILD_COMMIT"];
  if (fromEnv) return fromEnv;
  try {
    return (
      execFileSync("git", ["rev-parse", "--short", "HEAD"], {
        cwd: repoRoot,
        encoding: "utf8",
        stdio: ["ignore", "pipe", "ignore"],
      }).trim() || "unknown"
    );
  } catch {
    return "unknown";
  }
}

const pkg = JSON.parse(readFileSync(resolve(serverRoot, "package.json"), "utf8")) as {
  version: string;
};
const registry = JSON.parse(
  readFileSync(resolve(repoRoot, "release-names.json"), "utf8"),
) as Registry;

const info = {
  version: pkg.version,
  codename: codenameFor(pkg.version, registry),
  commit: resolveCommit(),
  buildDate: new Date().toISOString(),
};

const out = resolve(serverRoot, "src/build-info.generated.ts");
writeFileSync(
  out,
  `// Generated by scripts/gen-build-info.ts. Do not edit; not committed.\nexport const generated = ${JSON.stringify(info, null, 2)} as const;\n`,
);
console.log(`build-info: ${info.version} ${info.codename} ${info.commit}`);
